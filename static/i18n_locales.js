  /**
   * Retrieves localized string for given key in active language
   */
  function t(key, lang = 'en') {
    const selected = (lang || 'en').toLowerCase();
    const dict = I18N_DICTIONARY[selected] || I18N_DICTIONARY.en;
    return dict[key] || I18N_DICTIONARY.en[key] || key;
  }

  /**
   * Translates all elements with data-i18n attribute on page
   */
  function applyLanguageToDOM(lang = 'en') {
    const isRtl = lang === 'ar';
    document.documentElement.setAttribute('dir', isRtl ? 'rtl' : 'ltr');
    document.documentElement.setAttribute('lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.innerText = t(key, lang);
      }
    });
  }

